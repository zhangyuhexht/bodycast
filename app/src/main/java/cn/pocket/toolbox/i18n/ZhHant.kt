    private val CHAR_MAP: Map<Char, Char> by lazy {
        val map = HashMap<Char, Char>(CHAR_PAIRS.length / 2)
        var i = 0
        while (i + 1 < CHAR_PAIRS.length) {
            map[CHAR_PAIRS[i]] = CHAR_PAIRS[i + 1]
            i += 2
        }
        map
    }

    /** 词表按「长词优先」排序后使用（构造时排一次，运行期只是顺序扫描）。 */
    private val phrases: List<Pair<String, String>> by lazy {
        PHRASES.sortedByDescending { it.first.length }
    }

    /**
     * 简体中文 → 繁体中文（台湾用语）。
     * 已经是繁体 / 非中文的字符原样保留；英文缩写（App、Health Connect…）不动。
     */
    fun convert(source: String): String {
        if (source.isEmpty()) return source
        val sb = StringBuilder(source.length + 8)
        var i = 0
        while (i < source.length) {
            var matched = false
            for ((zh, tw) in phrases) {
                if (source.startsWith(zh, i)) {
                    sb.append(tw)
                    i += zh.length
                    matched = true
                    break
                }
            }
            if (!matched) {
                val c = source[i]
                sb.append(CHAR_MAP[c] ?: c)
                i++
            }
        }
        return sb.toString()
    }
